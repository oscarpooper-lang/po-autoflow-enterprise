export type TranslationKey = keyof typeof DICT.en;

export function tr(lang: UiLang, key: TranslationKey): string {
  return DICT[lang][key] || DICT.en[key];
}

export function tx(lang: UiLang, en: string, th: string): string {
  return lang === 'th' ? th : en;
}
